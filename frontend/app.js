composerForm.addEventListener("submit", () => {
  const data = new FormData(composerForm);
  const name = String(data.get("name")).trim();
  if (name === "") return;

  const date = String(data.get("date"));
  tasks.unshift({
    id: `t${String(Date.now())}`,
    type: date ? "EVENT" : "BASIC",
    name,
    status: "TODO",
    subtasks: [],
    ...(date ? { date: new Date(date).toISOString(), activeLogic: "NEXT_30_DAYS", passedDate: null, configTaskId: null } : {}),
  });

  activeFilter = stateOf(tasks[0]);
  announcer.textContent = `${name} added`;
  render();
});

